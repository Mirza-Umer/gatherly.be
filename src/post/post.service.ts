import {
  BadRequestException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { CreatePostDto } from './dto/create-post.dto';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { Post } from './entities/post.entity';
import { User } from '../users/entities/user.entity';
import { Like } from '../likes/entities/like.entity';
import { SavedPost } from './entities/savedPost.entity';

@Injectable()
export class PostService {
  constructor(
    @InjectRepository(Post)
    private readonly postRepo: Repository<Post>,

    @InjectRepository(Like)
    private readonly likeRepo: Repository<Like>,

    @InjectRepository(SavedPost)
    private readonly savedPostRepo: Repository<SavedPost>,
  ) {}

  // ✅ CREATE POST
  async create(
    createPostDto: CreatePostDto,
    user: User,
    file: Express.Multer.File,
  ) {
    if (!file) {
      throw new BadRequestException('Media file is required');
    }

    // Determine media type
    const mimeType = file.mimetype;
    let mediaType: 'image' | 'video';

    if (mimeType.startsWith('image/')) {
      mediaType = 'image';
    } else if (mimeType.startsWith('video/')) {
      mediaType = 'video';
    } else {
      throw new BadRequestException('Unsupported file type');
    }

    // Save file to uploads folder (filename already generated by Multer)
    const mediaUrl = `/uploads/${file.filename}`;

    // Create post in DB
    const post = this.postRepo.create({
      title: createPostDto.title,
      caption: createPostDto.caption,
      mediaUrls: [mediaUrl],
      mediaType: mediaType,
      user,
    });

    return await this.postRepo.save(post);
  }

  // ✅ GET ALL POSTS
  async getAllPosts(take = 10, page = 0, currentUser?: User) {
    const [posts, total] = await this.postRepo.findAndCount({
      order: { createdAt: 'DESC' },
      relations: ['user', 'likes', 'likes.user', 'savedByUsers'],
      take,
      skip: page * take,
    });

    const data = posts.map((post) => ({
      ...post,
      likesCount: post.likes.length,
      isLiked: post.likes.some((like) => like.user.id === currentUser?.id),
      isSaved:
        post.savedByUsers?.some((saved) => saved.id === currentUser?.id) ||
        false,
    }));

    return { data, total };
  }

  async getPostsByUserId(id: number) {
    const posts = await this.postRepo.find({
      where: { user: { id } },
      relations: ['user'],
      order: { createdAt: 'DESC' },
    });

    return { posts };
  }

  // ✅ GET SINGLE POST
  async getPostById(id: number) {
    const post = await this.postRepo.findOne({
      where: { id },
      relations: ['user'],
    });

    if (!post) {
      throw new NotFoundException('Post not found');
    }

    return post;
  }

  // ✅ SAVE POST
  async savePost(userId: number, postId: number) {
    const existing = await this.savedPostRepo.findOne({
      where: { user: { id: userId }, post: { id: postId } },
    });

    if (existing) {
      return { message: 'Already saved' };
    }

    const saved = this.savedPostRepo.create({
      user: { id: userId },
      post: { id: postId },
    });

    return await this.savedPostRepo.save(saved);
  }

  // ✅ UNSAVE POST
  async unsavePost(userId: number, postId: number) {
    await this.savedPostRepo.delete({
      user: { id: userId },
      post: { id: postId },
    });

    return { message: 'Post unsaved' };
  }

  // ✅ GET SAVED POSTS
  async getSavedPosts(userId: number) {
    const savedPosts = await this.savedPostRepo.find({
      where: { user: { id: userId } },
      relations: ['post', 'post.user'],
      order: { id: 'DESC' },
    });

    return savedPosts.map((item) => item.post);
  }
}
